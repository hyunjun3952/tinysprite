#!/usr/bin/env python3
"""Regenerate src/ui/icon_font.c from Material Symbols Outlined.

Needs fontTools (pip install fonttools) and the variable font from
https://github.com/google/material-design-icons (variablefont/MaterialSymbolsOutlined[...].ttf):

    scripts/gen-icon-font.py MaterialSymbolsOutlined.ttf src/ui/icon_font.c

Keeps only the glyphs listed in GLYPHS (code points from the font's .codepoints file) at weight 400,
optical size 24, unfilled. Adds "flip_v" (the "flip" glyph rotated 90 degrees) at U+E000.
"""
import io
import math
import sys

from fontTools import subset
from fontTools.misc.transform import Transform
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

GLYPHS = {
    "edit": 0xF097,
    "ink_eraser": 0xE6D0,
    "format_color_fill": 0xE23A,
    "colorize": 0xE3B8,
    "diagonal_line": 0xF41E,
    "crop_square": 0xE3C6,
    "circle": 0xEF4A,
    "highlight_alt": 0xEF52,
    "flip": 0xE3E8,
    "rotate_right": 0xE41A,
    "rotate_left": 0xE419,
    "swap_horiz": 0xE8D4,
    "add": 0xE145,
    "remove": 0xE15B,
    "content_copy": 0xE14D,
    "vertical_align_bottom": 0xE258,
    "arrow_upward": 0xE5D8,
    "arrow_downward": 0xE5DB,
    "open_in_new": 0xE89E,
}
FLIP_V = 0xE000


def main(src, out):
    font = TTFont(src)
    font = instancer.instantiateVariableFont(font, {"wght": 400, "opsz": 24, "FILL": 0, "GRAD": 0})
    options = subset.Options()
    options.layout_features = []
    options.notdef_outline = True
    options.hinting = False
    options.name_IDs = [1, 2]
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=list(GLYPHS.values()))
    subsetter.subset(font)

    flip = font.getBestCmap()[GLYPHS["flip"]]
    center = font["head"].unitsPerEm / 2
    pen = TTGlyphPen(font.getGlyphSet())
    rotate = Transform().translate(center, center).rotate(math.pi / 2).translate(-center, -center)
    font.getGlyphSet()[flip].draw(TransformPen(pen, rotate))
    order = font.getGlyphOrder() + ["flip_v"]
    font["glyf"]["flip_v"] = pen.glyph()
    font["glyf"].glyphOrder = order
    font.setGlyphOrder(order)
    font["hmtx"]["flip_v"] = font["hmtx"][flip]
    for table in font["cmap"].tables:
        if table.isUnicode():
            table.cmap[FLIP_V] = "flip_v"
    font["maxp"].numGlyphs = len(order)
    font["post"].formatType = 3.0
    buffer = io.BytesIO()
    font.save(buffer)
    data = buffer.getvalue()
    rows = [
        "    " + ", ".join("0x%02x" % b for b in data[i : i + 16]) + ","
        for i in range(0, len(data), 16)
    ]
    with open(out, "w") as f:
        f.write(
            '#include "icon_font.h"\n\n'
            "/* Generated by scripts/gen-icon-font.py from Material Symbols Outlined (Apache-2.0). */\n"
            "const unsigned char ICON_FONT_DATA[] = {\n" + "\n".join(rows) + "\n};\n\n"
            "const int ICON_FONT_SIZE = (int)sizeof(ICON_FONT_DATA);\n"
        )


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
