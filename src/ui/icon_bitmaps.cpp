const Bitmap *bitmap(Icon icon)
{
    switch (icon) {
    case Icon::Pencil:
        return &PENCIL;
    case Icon::Eraser:
        return &ERASER;
    case Icon::Bucket:
        return &BUCKET;
    case Icon::Eyedropper:
        return &EYEDROPPER;
    case Icon::Select:
        return &SELECT;
    case Icon::Slice:
        return &SLICE;
    case Icon::Line:
        return &LINE;
    case Icon::Rect:
        return &RECT;
    case Icon::Ellipse:
        return &ELLIPSE;
    case Icon::Triangle:
        return &TRIANGLE;
    case Icon::Diamond:
        return &DIAMOND;
    case Icon::Hexagon:
        return &HEXAGON;
    case Icon::Star:
        return &STAR;
    case Icon::Cross:
        return &CROSS;
    default:
        return nullptr;
    }
}

